<h3>📦 สำรอง/ย้ายข้อมูล (Import / Export)</h3>
<p>เมนู <strong>🗄️ Import/Export</strong> (Admin เท่านั้น) ใช้สำหรับสำรองข้อมูลหรือย้ายข้อมูลทั้งระบบไปเครื่องอื่น โดยไม่ต้องตั้งค่าทักษะ/กรรมการ/ทีมใหม่ทีละอย่าง:</p>
<ul>
  <li><strong>📤 Export</strong> — ดาวน์โหลดไฟล์ <code>.zip</code> เดียวที่รวม <code>database.sql</code> (ฐานข้อมูลทั้งหมด: ทักษะ กรรมการ ทีม กลุ่มเกณฑ์/เกณฑ์ย่อย การมอบหมาย คะแนน) และโฟลเดอร์ <code>uploads/</code> (ไฟล์เกณฑ์การแข่งขันที่อัปโหลดไว้) ไว้ด้วยกัน ใช้สำรองข้อมูลเป็นระยะระหว่างงาน หรือก่อนย้ายไปติดตั้งที่เครื่องอื่น</li>
  <li><strong>📥 Import</strong> — อัปโหลดไฟล์ <code>.zip</code> ที่ Export มา ระบบจะนำเข้าฐานข้อมูลและไฟล์ทั้งหมดให้อัตโนมัติ</li>
</ul>
<p style="background-color: #f8d7da; border-left: 5px solid #d9534f; padding: 15px">
  ⚠️ <strong>การ Import จะลบและแทนที่ข้อมูลปัจจุบันทั้งหมดในระบบ ไม่สามารถย้อนกลับได้</strong> — ต้องติ๊กยืนยันก่อนทุกครั้ง แนะนำให้ Export ข้อมูลปัจจุบันเก็บไว้ก่อน Import เสมอ
</p>
<p><strong>สำรองข้อมูลก่อนปิดระบบทุกครั้ง</strong> ด้วยเมนู Export ด้านบน (หรือจะสั่ง <code>mysqldump</code> ตรง ๆ ก็ได้ถ้าต้องการ):</p>
<pre><code class="language-bash">docker compose exec app mysqldump -h db -u judge_app -p"&lt;DB_PASSWORD ใน .env&gt;" judge_scoring > backup_judge_scoring.sql</code></pre>
<p>ปิดระบบ (ข้อมูลยังอยู่ครบ เปิดใหม่ครั้งหน้าด้วย <code>docker compose up -d</code> ได้ทันที):</p>
<pre><code class="language-bash">docker compose down</code></pre>
<p>หากต้องการ <strong>ล้างข้อมูลทั้งหมด</strong> เพื่อเริ่มงานแข่งขันครั้งใหม่ตั้งแต่ต้น (ลบฐานข้อมูลถาวร ย้อนกลับไม่ได้):</p>
<pre><code class="language-bash">docker compose down -v</code></pre>

