<h3>🧭 ลำดับการเตรียมระบบก่อนวันแข่งขัน (สำหรับ Admin)</h3>
<ol>
  <li><strong>ทักษะ</strong> — ตรวจสอบ/เพิ่มทักษะที่จะใช้แข่งขัน อัปโหลดไฟล์เกณฑ์การแข่งขัน (PDF) และรายละเอียดเพิ่มเติมได้ที่หน้านี้</li>
  <li>
    <strong>กลุ่มเกณฑ์การให้คะแนน</strong> — ระบบเตรียมเกณฑ์ไว้ล่วงหน้าตามไฟล์โจทย์ (รวมคำอธิบาย "วิธีตรวจ/เกณฑ์ได้คะแนน" ของแต่ละข้อ) แก้ไข/เพิ่ม/ลบเกณฑ์ย่อยได้ที่เมนูนี้
    <ul>
      <li>แต่ละหน้าเกณฑ์ย่อยมีลิงก์ <strong>ชื่อเกณฑ์</strong> และ <strong>⬅️ กลับไปหน้ากลุ่มเกณฑ์การให้คะแนน</strong> ด้านบนเสมอ เพื่อให้รู้ว่ากำลังแก้ไขเกณฑ์ของทักษะ/กลุ่มใดอยู่ เมื่อเปิดจากหลายทักษะพร้อมกัน</li>
      <li><strong>สำคัญ:</strong> หัวข้อ "โจทย์พิเศษ" (ฝั่ง DevOps) ต้องแก้ไขเนื้อหาให้ตรงกับโจทย์ที่จับฉลากได้จริงก่อนเริ่มแข่งขัน เพราะเกณฑ์แต่ละโจทย์แตกต่างกัน</li>
    </ul>
  </li>
  <li><strong>ทีมผู้เข้าแข่งขัน</strong> — เพิ่ม/แก้ไขชื่อทีมและโจทย์ที่จับได้</li>
  <li><strong>กรรมการ</strong> — เพิ่มกรรมการ ตั้งชื่อผู้ใช้/รหัสผ่าน กำหนด <strong>ตำแหน่ง</strong> และ <strong>กลุ่มเกณฑ์ที่รับผิดชอบ</strong> (กรรมการจะเห็นและให้คะแนนได้เฉพาะกลุ่มเกณฑ์ที่ได้รับมอบหมาย) — มีตัวกรองตามทักษะในหน้านี้เมื่อมีหลายทักษะ</li>
  <li><strong>มอบหมายทีม</strong> (เมนูนี้ของประธานกรรมการ) — ถ้าต้องการจำกัดว่ากรรมการแต่ละคนให้คะแนนได้เฉพาะบางทีม ให้ตั้งที่เมนูนี้ (ถ้าไม่ตั้ง กรรมการจะให้คะแนนได้ทุกทีมในกลุ่มเกณฑ์ของตนตามปกติ)</li>
  <li>
    <strong>ใบให้คะแนน (สำรอง)</strong> — หน้าเลือกทีม+กรรมการมีลิงก์กลับไปหน้ากลุ่มเกณฑ์เช่นเดียวกับข้อ 2 เมื่อเลือกแล้วกด "สร้างและพิมพ์" จะได้ใบประเมินคะแนนกระดาษ
    (บันทึกเป็น PDF ได้) ไว้ล่วงหน้าเป็นแผนสำรอง กรณีระบบคอมพิวเตอร์ใช้งานไม่ได้ขณะแข่งขัน — รายชื่อกรรมการในแต่ละใบถูก <strong>เรียงลำดับตามตำแหน่งอัตโนมัติ</strong>
    (ประธานกรรมการ → รองประธานกรรมการ → กรรมการ → กรรมการและเลขานุการ → ผู้ช่วยกรรมการและเลขานุการ) เลือกได้หลายคู่ทีม+กรรมการพร้อมกัน พิมพ์ครั้งเดียว
  </li>
  <li>
    <strong>📖 เกณฑ์การให้คะแนน (สำหรับกรรมการ)</strong> — แจกลิงก์นี้ให้กรรมการทุกคนเปิดอ่าน <strong>ก่อนเริ่มให้คะแนนจริง</strong> ติ๊กเลือกกลุ่มเกณฑ์ที่ต้องการ
    แล้วพิมพ์/บันทึกเป็น PDF ได้เอกสารรวมหัวข้อใหญ่ (กลุ่มเกณฑ์) หัวข้อย่อย และวิธีตรวจ/เกณฑ์การให้คะแนนของทุกข้อไว้ในเล่มเดียว (ไม่มีช่องกรอกคะแนน ใช้อ่านเตรียมตัวเท่านั้น
    ต่างจากใบให้คะแนนในข้อ 6) ดูรายละเอียดที่หัวข้อ "📖 เอกสารเกณฑ์การให้คะแนนสำหรับกรรมการ" ด้านล่าง
  </li>
</ol>

