<h3>🔒 หมายเหตุด้านความปลอดภัย</h3>
<ul>
  <li>รหัสผ่านถูกเก็บด้วย <code>password_hash</code> (bcrypt) ไม่มีการเก็บรหัสผ่านแบบ plain text</li>
  <li>ทุกฟอร์มมีการตรวจ CSRF token</li>
  <li>ทุกคำสั่ง SQL ใช้ Prepared Statement ป้องกัน SQL Injection</li>
  <li>โค้ดฝั่ง <code>app/</code> อยู่นอก DocumentRoot ของ Apache เข้าถึงผ่านเว็บไม่ได้โดยตรง</li>
  <li>ไฟล์เอกสารเกณฑ์ที่อัปโหลดเก็บนอก DocumentRoot เช่นกัน เข้าถึงได้เฉพาะผู้ที่ Login แล้วเท่านั้น (ผ่าน <code>download_criteria.php</code>)</li>
  <li><strong>อย่า commit ไฟล์ <code>.env</code> จริงขึ้น Git</strong> (ถูกกันไว้ใน <code>.gitignore</code> แล้ว) และอย่าใช้รหัสผ่านตัวอย่างจาก <code>.env.example</code> ในงานจริง</li>
</ul>

