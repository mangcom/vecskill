<h1>ระบบให้คะแนนกรรมการ (Vocational Skill Judging System)</h1>
<p>
  <strong>Vocational Skill Judging System (VSJS)</strong> เป็นเว็บแอปสำหรับกรรมการบันทึกคะแนนการแข่งขันทักษะวิชาชีพ (ปวส./ปวช.) โดยเฉพาะ
  พัฒนาแยกเป็นอีกโปรเจกต์หนึ่งต่างหากจากคู่มือนี้ (โดยผู้พัฒนาคนเดียวกัน) เหมาะสำหรับ <strong>ผู้จัดการแข่งขัน/ประธานกรรมการ</strong>
  ที่ต้องการระบบบันทึกคะแนนพร้อมใช้งาน ไม่ต้องเขียนเอง — ติดตั้งบนเครื่องคอมพิวเตอร์เครื่องเดียวที่งานแข่งขัน แล้วให้กรรมการเชื่อมต่อผ่าน Wi-Fi/LAN
  วงเดียวกันด้วยมือถือ/โน้ตบุ๊กของตัวเอง <strong>ไม่ต้องใช้อินเทอร์เน็ตระหว่างแข่งขัน</strong>
</p>

