<h3>📖 เอกสารเกณฑ์การให้คะแนนสำหรับกรรมการ</h3>
<p>
  เมนู <strong>📖 เกณฑ์การให้คะแนน</strong> (เห็นได้ทั้ง Admin และกรรมการทุกคน ที่ <code>/criteria_doc</code>) ใช้สร้างเอกสาร PDF ให้กรรมการอ่านทำความเข้าใจเกณฑ์การแข่งขันโดยละเอียด
  <strong>ก่อนเริ่มให้คะแนนจริง</strong>:
</p>
<ul>
  <li>เลือกทักษะที่ต้องการ (สลับได้จากตัวเลือกทักษะด้านบนของเนื้อหาเมื่อมีหลายทักษะ) แล้วติ๊กเลือกกลุ่มเกณฑ์ (ค่าเริ่มต้นติ๊กไว้ทุกกลุ่ม) กด <strong>🖨️ สร้างและพิมพ์เอกสาร</strong></li>
  <li>เอกสารที่ได้มีหน้าปกสรุปรายการกลุ่มเกณฑ์ทั้งหมด + คะแนนเต็ม ตามด้วยเนื้อหาของแต่ละกลุ่มเกณฑ์ที่เลือก เรียงเป็น <strong>หัวข้อใหญ่ (กลุ่มเกณฑ์/ส่วนที่) → หัวข้อย่อย (ถ้ามี) → รายการเกณฑ์ย่อยพร้อมวิธีตรวจ/เกณฑ์ได้คะแนน และคะแนนเต็มของแต่ละข้อ</strong></li>
  <li><strong>ไม่มีช่องกรอกคะแนน</strong> — ต่างจากเมนู "🖨️ ใบให้คะแนน (สำรอง)" ที่ใช้เป็นแบบฟอร์มกรอกคะแนนจริง เอกสารนี้มีไว้ให้อ่านเตรียมตัวเท่านั้น เหมาะสำหรับแจกกรรมการทุกคนล่วงหน้าหรือให้อ่านก่อนวันแข่งขัน</li>
  <li>ถ้า Admin อัปโหลดไฟล์เกณฑ์การแข่งขันต้นฉบับ (PDF ทางการ) ไว้ที่เมนู "ทักษะ" แล้ว หน้านี้จะมีลิงก์ดาวน์โหลดไฟล์ต้นฉบับนั้นให้ด้วย</li>
</ul>

