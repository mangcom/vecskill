<h3># ระบบให้คะแนนกรรมการ (Vocational Skill Judging System – VSJS)</h3>
<p>
  เว็บแอปสำหรับกรรมการบันทึกคะแนนการแข่งขันทักษะวิชาชีพ (ปวส./ปวช.) รองรับหลาย <strong>ทักษะ</strong> ในระบบเดียว โดยค่าเริ่มต้นมี 2 ทักษะ:
</p>
<ul>
  <li><strong>ปวส. - ทักษะเทคโนโลยีสารสนเทศด้านโปรแกรมและเครือข่ายด้วยกระบวนการ DevOps</strong> (ส่วนที่ 1–5 รวม 100 คะแนน + โจทย์พิเศษ 10 คะแนนแยกไว้จัดอันดับ)</li>
  <li><strong>ปวช. - ทักษะการพัฒนาระบบประเมินบุคลากรด้วยระบบเทคโนโลยีสารสนเทศสมัยใหม่</strong> (ส่วนที่ 1–9 รวม 100 คะแนน)</li>
</ul>
<p>
  แต่ละทักษะมีทีม กรรมการที่รับผิดชอบ กลุ่มเกณฑ์การให้คะแนน/เกณฑ์ย่อย และสรุปคะแนนแยกจากกันโดยสิ้นเชิง สามารถเพิ่มทักษะใหม่ได้จากเมนู "ทักษะ" (Admin เท่านั้น)
</p>
<p>
  ระบบนี้ถูกออกแบบให้ <strong>ติดตั้งและรันบนเครื่องคอมพิวเตอร์ที่งานแข่งขัน</strong> (เช่น โน้ตบุ๊กของฝ่ายจัดการแข่งขัน/ประธานกรรมการ) แล้วให้กรรมการและกรรมการตรวจแต่ละคนเปิดเบราว์เซอร์จากมือถือ/โน้ตบุ๊กของตัวเอง
  เชื่อมต่อผ่าน Wi-Fi/LAN วงเดียวกันมาที่เครื่องนี้ — <strong>ไม่จำเป็นต้องมีอินเทอร์เน็ต</strong> ขณะแข่งขัน (ยกเว้นตอนโหลดฟอนต์ Saraban ครั้งแรกของแต่ละเครื่องที่เข้าใช้)
</p>
<p style="background-color: #d1ecf1; border-left: 5px solid #0c5460; padding: 15px">
  📘 <strong>เอกสารนี้ใช้สำหรับวิทยาลัย/หน่วยงานที่นำระบบนี้ไปติดตั้งใช้งานจัดการแข่งขันทักษะของตนเอง</strong> ไล่อ่านตามลำดับหัวข้อได้ตั้งแต่ข้อกำหนดของเครื่อง → วิธีติดตั้ง → การเตรียมข้อมูลก่อนแข่งขัน → วิธีใช้งานสำหรับกรรมการ
  มีคู่มือฉบับเต็มเป็น PDF ให้ดาวน์โหลด/พิมพ์แจกกรรมการได้ที่เมนู <strong>❓ คู่มือการใช้งาน</strong> ในระบบ (ดูหัวข้อ "❓ คู่มือการใช้งาน" ด้านล่าง)
</p>

<h3>✨ ฟีเจอร์เด่น</h3>
<ul>
  <li>รองรับหลายทักษะ/หลายการแข่งขันในระบบเดียว แยกทีม กรรมการ เกณฑ์ และคะแนนกันอย่างอิสระ</li>
  <li><strong>เมนูด้านซ้าย (Sidebar)</strong> ย่อ/ขยายได้ (กดไอคอน ☰ มุมซ้ายบน) บนมือถือจะซ่อนเป็นเมนูเลื่อนออกมาแทน</li>
  <li>กรรมการแต่ละคนเห็น/ให้คะแนนได้เฉพาะกลุ่มเกณฑ์ที่ตนรับผิดชอบเท่านั้น</li>
  <li>ประธานกรรมการและกรรมการและเลขานุการของแต่ละกลุ่มเกณฑ์ <strong>แก้ไขเกณฑ์การให้คะแนนของตนเองได้โดยไม่ต้องรอ Admin</strong></li>
  <li>พิมพ์เอกสารเกณฑ์การแข่งขันและใบให้คะแนนกระดาษสำรองเป็น PDF ได้จากในระบบโดยตรง</li>
  <li>ทุกบัญชีแก้ไขข้อมูลส่วนตัว อัปโหลดรูปโปรไฟล์ เปลี่ยนรหัสผ่าน และเปิดใช้การยืนยันตัวตน 2 ขั้นตอน (2FA) ได้ด้วยตนเองที่หน้าโปรไฟล์</li>
  <li>สำรอง/ย้ายข้อมูลทั้งระบบไปเครื่องอื่นได้ในไฟล์ <code>.zip</code> เดียว เหมาะกับการใช้ซ้ำในหลายสนามแข่ง/หลายระดับ (สถานศึกษา → จังหวัด → ภาค → ชาติ)</li>
</ul>

