<h3>✏️ สิทธิ์แก้ไขเกณฑ์การให้คะแนน</h3>
<p>
  นอกจาก Admin แล้ว <strong>ประธานกรรมการ</strong> และ <strong>กรรมการและเลขานุการ</strong> ของแต่ละกลุ่มเกณฑ์สามารถแก้ไขเกณฑ์การให้คะแนน (เพิ่ม/แก้ไข/ลบหัวข้อและเกณฑ์ย่อย)
  ของกลุ่มเกณฑ์ที่ตนเองรับผิดชอบได้ด้วยตนเอง โดยกดปุ่ม <strong>✏️ แก้ไขเกณฑ์</strong> ที่หน้า <strong>เกณฑ์การให้คะแนน</strong> (<code>/criteria_doc</code>) ของตนเอง —
  แก้ไขได้เฉพาะกลุ่มเกณฑ์ที่ได้รับมอบหมายเท่านั้น
</p>
<p>
  หน้า <strong>เกณฑ์การให้คะแนน</strong> (<code>/criteria_doc</code>) ของกรรมการ (ไม่ใช่ Admin) จะแสดง<strong>เฉพาะกลุ่มเกณฑ์ที่ตนเองรับผิดชอบ</strong>เท่านั้น ไม่แสดงกลุ่มเกณฑ์อื่นในทักษะเดียวกัน
</p>

<h3>📊 หลักการคำนวณคะแนนรวม</h3>
<ul>
  <li>คะแนนแต่ละข้อของทีม = <strong>ค่าเฉลี่ย</strong> ของคะแนนจากกรรมการทุกคนที่บันทึกไว้สำหรับข้อนั้น (ถ้ามีกรรมการมากกว่า 1 คนรับผิดชอบกลุ่มเกณฑ์เดียวกัน)</li>
  <li>คะแนนรวมของกลุ่มเกณฑ์ = ผลรวมคะแนนเฉลี่ยของทุกข้อในกลุ่มเกณฑ์นั้น</li>
  <li>คะแนนรวม 100 = ผลรวมคะแนนของกลุ่มเกณฑ์หลัก โดยไม่รวมโจทย์พิเศษ</li>
  <li>โจทย์พิเศษ (ฝั่ง DevOps, เต็ม 10) แยกออกจากคะแนน 100 ใช้สำหรับจัดอันดับเมื่อคะแนนรวมเท่ากันเท่านั้น</li>
</ul>

