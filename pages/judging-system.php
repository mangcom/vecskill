<h3>🚀 วิธีติดตั้งและเริ่มใช้งาน (เครื่องกรรมการ / เครื่องเซิร์ฟเวอร์ประจำสนามแข่ง)</h3>

<h4>1. ติดตั้ง Docker Desktop</h4>
<p>ดาวน์โหลดและติดตั้งจาก <a href="https://www.docker.com/products/docker-desktop/" target="_blank">https://www.docker.com/products/docker-desktop/</a> แล้วเปิดโปรแกรม Docker Desktop ทิ้งไว้ (ไอคอนวาฬที่มุมล่างขวาต้องขึ้นสถานะ "Running")</p>

<h4>2. ดึงโค้ดระบบลงเครื่อง</h4>
<p>ถ้าเครื่องมี Git ติดตั้งอยู่แล้ว:</p>
<pre><code class="language-bash">git clone https://github.com/mangcom/Vocational-Skill-Judging-System.git
cd Vocational-Skill-Judging-System</code></pre>
<p>หรือถ้าไม่สะดวกใช้ Git ให้ดาวน์โหลดเป็นไฟล์ ZIP จากหน้า GitHub ของ repo (ปุ่ม <strong>Code → Download ZIP</strong>) แล้วแตกไฟล์ไว้ในเครื่อง</p>

<h4>3. ตั้งค่าไฟล์ <code>.env</code></h4>
<p>
  คัดลอกไฟล์ตัวอย่างไว้ก่อน (ค่าด้านในเป็นเพียงค่าเริ่มต้น/fallback — จะตั้งรหัสผ่าน Admin และตรวจสอบการเชื่อมต่อฐานข้อมูลจริงผ่านหน้าเว็บ
  <code>/install.php</code> ในขั้นตอนที่ 7 แทนการแก้ไฟล์เอง):
</p>
<pre><code class="language-bash">cp .env.example .env</code></pre>
<p>
  ถ้าต้องการเปลี่ยนพอร์ตที่ใช้เปิดเว็บ (ค่าเริ่มต้น <code>8080</code>) หรือรหัสผ่านระดับ root ของฐานข้อมูล (<code>DB_ROOT_PASSWORD</code>) ให้แก้ในไฟล์ <code>.env</code>
  ก่อนรันขั้นตอนถัดไป (ค่าที่เหลือ — <code>DB_NAME</code>/<code>DB_USER</code>/<code>DB_PASSWORD</code>/บัญชี Admin — ตั้งผ่านหน้าเว็บได้เลย ไม่จำเป็นต้องแก้ในไฟล์ล่วงหน้า):
</p>
<pre><code>APP_PORT=8080
DB_ROOT_PASSWORD=&lt;ตั้งรหัสผ่านใหม่&gt;</code></pre>

<h4>4. สั่งสร้างและรันระบบ</h4>
<pre><code class="language-bash">docker compose up -d --build</code></pre>
<p>รอสักครู่ (ครั้งแรกจะดาวน์โหลด image และสร้างฐานข้อมูล ~1-2 นาที) ตรวจสอบว่าเริ่มสำเร็จด้วย:</p>
<pre><code class="language-bash">docker compose logs app --tail 30</code></pre>
<p>ควรเห็นบรรทัด <code>[migrate] done</code> และ Apache เริ่มทำงาน (ไม่มี error สีแดง)</p>

<h4>5. ทดสอบเปิดจากเครื่องตัวเอง</h4>
<p>เปิดเบราว์เซอร์ไปที่ <code>http://localhost:8080</code> ควรเห็นหน้า Login</p>

<h4>6. หา IP ของเครื่องนี้ เพื่อให้กรรมการคนอื่นเชื่อมต่อ</h4>
<p>บน Windows เปิด PowerShell แล้วพิมพ์:</p>
<pre><code class="language-powershell">ipconfig</code></pre>
<p>
  ดูที่ <code>IPv4 Address</code> ของการ์ดเครือข่ายที่ต่อ Wi-Fi/LAN เดียวกับกรรมการ (เช่น <code>192.168.1.50</code>) แล้วแจ้งให้กรรมการแต่ละคนเปิดเบราว์เซอร์
  (มือถือ/โน้ตบุ๊กของตัวเอง) ไปที่:
</p>
<pre><code>http://192.168.1.50:8080</code></pre>
<p>(แทน <code>192.168.1.50</code> ด้วย IP จริงของเครื่องที่รันระบบ)</p>
<p style="background-color: #fff3cd; border-left: 5px solid #ffeeba; padding: 15px">
  ⚠️ <strong>ถ้าเปิดจากเครื่องอื่นแล้วเข้าไม่ได้</strong> ให้ตรวจสอบ <strong>Windows Firewall</strong> ของเครื่องที่รันระบบ — ไปที่ Windows Defender Firewall →
  Allow an app through firewall → อนุญาต "Docker Desktop Backend" ทั้ง Private และ Public network หรือเปิดพอร์ต 8080 (TCP) แบบ Inbound Rule ชั่วคราวระหว่างงานแข่งขัน
</p>

<h4>7. ติดตั้งระบบผ่านเว็บ (<code>/install</code>) — ตั้งรหัสผ่าน Admin และตรวจการเชื่อมต่อฐานข้อมูล</h4>
<p>เปิดเบราว์เซอร์ไปที่ <code>http://localhost:8080/install</code> (หน้านี้จะแสดง <strong>เฉพาะครั้งแรก</strong> ที่ยังไม่มีบัญชี Admin ในระบบ) แล้วกรอก:</p>
<ul>
  <li><strong>Database Hostname</strong> — ค่าเริ่มต้นอ่านจาก <code>.env</code> (ใช้ <code>db</code> ตามเดิมถ้าใช้ docker-compose ที่แนบมา)</li>
  <li><strong>Database Name / User / Password</strong> — ปล่อยเป็นค่าเริ่มต้นได้ถ้าใช้ฐานข้อมูลที่แนบมากับ docker-compose</li>
  <li><strong>Admin Username / Password</strong> — ตั้งเป็นของจริง (ห้ามใช้ <code>admin</code> / <code>Admin@2569</code> ตามตัวอย่างในงานจริง)</li>
</ul>
<p>กด <strong>🚀 ติดตั้งระบบ</strong> ระบบจะสร้างตารางฐานข้อมูล สร้างบัญชี Admin ตามที่กรอก และบันทึกค่าทั้งหมดลงไฟล์ <code>.env</code> ให้อัตโนมัติ จากนั้นเข้าสู่ระบบด้วยบัญชี Admin ที่เพิ่งตั้งได้ทันที</p>
<p style="background-color: #d1ecf1; border-left: 5px solid #0c5460; padding: 15px">
  หน้า <code>/install</code> จะถูกล็อกอัตโนมัติหลังติดตั้งสำเร็จ (เข้าซ้ำจะเด้งไปหน้า Login) ถ้าต้องการเปลี่ยนค่าการเชื่อมต่อฐานข้อมูล/บัญชี Admin ภายหลัง
  ให้ Login ด้วยบัญชี Admin ปัจจุบันก่อน แล้วเปิด <code>/install</code> อีกครั้ง<br /><br />
  💡 ระบบรองรับ <strong>Clean URL</strong> (ไม่ต้องมี <code>.php</code> ต่อท้าย) ทุกหน้า เช่น <code>/admin/judges</code> แทน <code>/admin/judges.php</code> —
  ลิงก์ทุกจุดในระบบสร้างเป็น Clean URL ให้อัตโนมัติ แต่ถ้าพิมพ์ URL เดิมที่มี <code>.php</code> ต่อท้ายก็ยังเปิดได้ตามปกติ
</p>

<h4>8. (ถ้ามีไฟล์สำรองข้อมูลจากเครื่องอื่น) นำเข้าข้อมูลทันทีผ่านเมนู Import/Export</h4>
<p>
  ถ้าเตรียมข้อมูลทักษะ/กรรมการ/ทีมไว้แล้วจากเครื่องอื่น ไม่ต้องตั้งค่าใหม่ทั้งหมด — ไปที่เมนู <strong>🗄️ Import/Export</strong> หลัง Login
  แล้วอัปโหลดไฟล์ <code>.zip</code> ที่ Export มาจากเครื่องเดิม ระบบจะนำเข้าข้อมูลทั้งหมด (รวมไฟล์เกณฑ์ที่เคยอัปโหลด) มาแทนที่ข้อมูลเริ่มต้นให้ทันที
  (ดูรายละเอียดที่หัวข้อ "📦 สำรอง/ย้ายข้อมูล (Import / Export)" ด้านล่าง)
</p>

